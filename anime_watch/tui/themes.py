_ORDER = list(THEMES)


def theme_names() -> list[str]:
    return list(_ORDER)


def next_theme(current: str) -> str:
    if current not in _ORDER:
        return _ORDER[0]
    return _ORDER[(_ORDER.index(current) + 1) % len(_ORDER)]
